async function persona(nombre, viewport = { width: 390, height: 844 }) {
  const ctx = await navegador.newContext({ viewport, hasTouch: true, permissions: [] })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => errores.push(`[${nombre}] ${e.message}`))
  page.on('console', (m) => { if (m.type() === 'error' && !/400|401|403|409|422|Failed to load resource|camera|NotAllowed|Requested device/i.test(m.text())) errores.push(`[${nombre}] ${m.text()}`) })
  page.on('dialog', (d) => d.accept())
  await page.route(`${SUPA}/**`, (r) => r.fulfill({ status: 200, body: r.request().method() === 'GET' ? PNG : '{}', contentType: 'image/png', headers: { 'access-control-allow-origin': '*' } }))
  await page.route(`${API}/api/publicaciones/fotos`, async (r) => {
    const uid = await page.evaluate(() => JSON.parse(localStorage.getItem('cvd_sesion')).usuario.id)
    const nombre = `${randomUUID()}.jpg`
    r.fulfill({ json: { url_subida: `${SUPA}/subida/${nombre}?token=t`, url_publica: `${SUPA}/storage/v1/object/public/publicaciones/${uid}/${nombre}` }, headers: { 'access-control-allow-origin': WEB } })
  })
  return { ctx, page }
}
